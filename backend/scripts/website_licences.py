"""Generate the website's licence page from the files the app ships — so site and app say the same thing.

Run from ``backend/``::

    uv run python scripts/website_licences.py          # write the page and its two text files
    uv run python scripts/website_licences.py --check  # exit 1 if anything on the site is stale

Sources (nothing here is typed twice):

* ``LICENSE`` — PrismLCA's licence. The app ships it as ``frontend/resources/LICENSE.txt``; the site
  shows it verbatim and offers the identical file. ``--check`` also fails if the app's copy differs.
* ``THIRD-PARTY-NOTICES.md`` — generated by ``third_party_notices.py`` (run that first after a
  dependency change). The site shows its "## Summary" tables, cut exactly as the app's notices sheet
  cuts them (``summarySection`` in ``frontend/src/main/licence.ts``), and offers the identical file.
* ``frontend/src/shared/licence.ts`` — the licence name and the sentences the app's sheets open with.
* ``Website2/index.html`` — navigation and footer, so the page looks like the rest of the site.

Outputs, all in the site folder (``Website2/``, ``--site`` or ``$PRISM_SITE_DIR``): ``licenses.html``, ``LICENSE.txt``, ``THIRD-PARTY-NOTICES.md``.
The output is deterministic; only the inputs above change it.
"""

from __future__ import annotations

import argparse
import html
import os
import re
import sys
from pathlib import Path

SCRIPTS = Path(__file__).resolve().parent
REPO = SCRIPTS.parent.parent
# The site folder: Website2/ next to the code, or a separate checkout of the website repository —
# pass --site or set PRISM_SITE_DIR. Run before every deploy.
SITE = Path(os.environ.get("PRISM_SITE_DIR") or REPO / "Website2")
LICENSE = REPO / "LICENSE"
APP_LICENSE = REPO / "frontend" / "resources" / "LICENSE.txt"
NOTICES = REPO / "THIRD-PARTY-NOTICES.md"
SHARED = REPO / "frontend" / "src" / "shared" / "licence.ts"

PAGE = SITE_LICENSE = SITE_NOTICES = Path()


def use_site(site: Path) -> None:
    global SITE, PAGE, SITE_LICENSE, SITE_NOTICES
    SITE = site
    PAGE, SITE_LICENSE, SITE_NOTICES = SITE / "licenses.html", SITE / "LICENSE.txt", SITE / "THIRD-PARTY-NOTICES.md"


use_site(SITE)


def shared_constants() -> dict[str, str]:
    """``export const NAME = '...'`` from shared/licence.ts (Prettier may break after the ``=``)."""
    text = SHARED.read_text(encoding="utf-8")
    found = dict(re.findall(r"export const (\w+) =\s*'((?:[^'\\]|\\.)*)'", text))
    need = ("LICENCE_LABEL", "LICENCE_NAME", "NOTICES_LABEL", "LICENCE_BLURB", "NOTICES_BLURB", "NOTICES_PROVENANCE")
    missing = [n for n in need if n not in found]
    if missing:
        raise SystemExit(f"{SHARED.relative_to(REPO)}: constants not found: {', '.join(missing)}")
    return {k: v.replace("\\'", "'") for k, v in found.items()}


def summary_section(md: str) -> str:
    """Same cut as ``summarySection`` in frontend/src/main/licence.ts: from "## Summary" to the next
    second-level heading."""
    start = md.find("\n## Summary")
    if start < 0:
        return ""
    rest = md[start + 1:]
    nxt = rest.find("\n## ", 1)
    return (rest if nxt < 0 else rest[:nxt]).strip()


def notices_header(md: str) -> dict[str, str]:
    """Version, commit and package counts from the notices' first lines (older files also carry a date)."""
    out = {}
    if m := re.search(r"^PrismLCA version ([^\s]+)\.", md, re.M):
        out["version"] = m.group(1)
    if m := re.search(r"^Generated from git commit (\w+)(?: \(([\d-]+)\))?", md, re.M):
        out["commit"] = m.group(1)
        if m.group(2):
            out["date"] = m.group(2)
    if m := re.search(r"^(\d+) Python runtime packages, (\d+) npm packages\.", md, re.M):
        out["python"], out["npm"] = m.group(1), m.group(2)
    return out


def inline(text: str) -> str:
    """Markdown inline code and links, escaped — all the summary section uses."""
    out = html.escape(text)
    out = re.sub(r"`([^`]+)`", r"<code>\1</code>", out)
    return out


def summary_html(section: str) -> str:
    """The summary's ### headings, paragraphs and pipe tables as HTML; each table in a <details>."""
    blocks: list[str] = []
    lines = section.splitlines()[1:]  # drop "## Summary"
    i = 0
    while i < len(lines):
        line = lines[i]
        if line.startswith("### "):
            title = line[4:].strip()
            j = i + 1
            para: list[str] = []
            while j < len(lines) and not lines[j].startswith("|") and not lines[j].startswith("### "):
                if lines[j].strip():
                    para.append(lines[j].strip())
                j += 1
            rows: list[list[str]] = []
            while j < len(lines) and lines[j].startswith("|"):
                cells = [c.strip() for c in lines[j].strip().strip("|").split("|")]
                if not all(re.fullmatch(r":?-{3,}:?", c) for c in cells):
                    rows.append(cells)
                j += 1
            body = ""
            if para:
                body += f'<p class="lic-note">{inline(" ".join(para))}</p>'
            if rows:
                head, data = rows[0], rows[1:]
                th = "".join(f"<th>{inline(c)}</th>" for c in head)
                trs = "\n".join("<tr>" + "".join(f"<td>{inline(c)}</td>" for c in r) + "</tr>" for r in data)
                body += f'<div class="lic-table-wrap"><table class="lic-table"><thead><tr>{th}</tr></thead><tbody>\n{trs}\n</tbody></table></div>'
            blocks.append(f'<details class="lic-details"><summary>{inline(title)}</summary>{body}</details>')
            i = j
        else:
            i += 1
    return "\n".join(blocks)


def chrome() -> tuple[str, str]:
    """Navigation and footer from the home page, with in-page links pointed at it."""
    s = (SITE / "index.html").read_text(encoding="utf-8")
    nav = s[s.index('<header class="nav" id="nav">'): s.index("</header>") + len("</header>")]
    foot = s[s.index('<footer class="footer">'): s.index("</footer>") + len("</footer>")]
    # `#top` stays: an internal way back to the start page carries a fragment, and the start page skips its
    # intro animation for it — the cue that replaced remembering the intro in sessionStorage (§ 25 TDDDG).
    for a, b in (('href="#top"', 'href="index.html#top"'), ('href="#download"', 'href="index.html#download"'),
                 ('href="#open"', 'href="index.html#open"'), ('href="#product-video"', 'href="index.html#product-video"')):
        nav, foot = nav.replace(a, b), foot.replace(a, b)
    foot = foot.replace('<a href="licenses.html">Licences</a>', '<a href="licenses.html" aria-current="page">Licences</a>')
    return nav, foot


def build() -> dict[Path, str]:
    c = shared_constants()
