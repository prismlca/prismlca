def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--check", action="store_true", help="do not write; exit 1 if anything is stale")
    parser.add_argument("--site", type=Path, help="the site folder (default: Website2/ or $PRISM_SITE_DIR)")
    args = parser.parse_args(argv)
    if args.site:
        use_site(args.site.resolve())
    status = 0
    if LICENSE.read_bytes() != APP_LICENSE.read_bytes():
        print(f"DIFFERS {APP_LICENSE.relative_to(REPO)} is not a copy of LICENSE", file=sys.stderr)
        status = 1
    outputs = build()
    if args.check:
        for path, text in outputs.items():
            current = path.read_text(encoding="utf-8") if path.exists() else ""
            if current != text:
                print(f"STALE {path}", file=sys.stderr)
                status = 1
        if status:
            print("Regenerate: cd backend && uv run python scripts/website_licences.py", file=sys.stderr)
    else:
        for path, text in outputs.items():
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {path} ({len(text.encode('utf-8'))} bytes)")
    return status


if __name__ == "__main__":
    sys.exit(main())
